def main():
    rows = []
    for q, doc, sec, gold in SINGLE + MULTI:
        rows.append({
            "question": q, "qtype": "single" if (q, doc, sec, gold) in SINGLE else "multi",
            "doc_title": doc, "section_title": sec,
            "expected_answer": gold, "answerable": True,
        })
    # 修正 qtype（SINGLE/MULTI 分开写更清晰）
    rows = []
    for item, t in ((SINGLE, "single"), (MULTI, "multi")):
        for q, doc, sec, gold in item:
            rows.append({
                "question": q, "qtype": t, "doc_title": doc,
                "section_title": sec, "expected_answer": gold, "answerable": True,
            })
    for q, docs, sec, gold in MULTIHOP:
        rows.append({
            "question": q, "qtype": "multihop", "doc_titles": docs,
            "doc_title": docs[0], "section_title": sec,
            "expected_answer": gold, "answerable": True,
        })
    for q, doc, gold in SUMMARY:
        rows.append({
            "question": q, "qtype": "summary", "doc_title": doc,
            "section_title": None, "expected_answer": gold, "answerable": True,
        })
    for q, docs, sec, gold in COMPARE:
        rows.append({
            "question": q, "qtype": "compare", "doc_titles": docs,
            "doc_title": docs[0], "section_title": sec,
            "expected_answer": gold, "answerable": True,
        })
    for q, why in NOANSWER:
        rows.append({
            "question": q, "qtype": "noanswer", "doc_title": None,
            "section_title": None, "expected_answer": None, "answerable": False,
            "why_not_in_corpus": why,
        })

    OUT.write_text(
        "\n".join(json.dumps(r, ensure_ascii=False) for r in rows) + "\n",
        encoding="utf-8",
    )

    from collections import Counter
    c = Counter(r["qtype"] for r in rows)
    print("=" * 76)
    print(f"写入 {OUT}")
    print("=" * 76)
    for t in ("single", "multi", "multihop", "summary", "compare", "noanswer"):
        print(f"  {t:<10} {c.get(t,0)}")
    print(f"  {'合计':<10} {len(rows)}")


if __name__ == "__main__":
    main()
